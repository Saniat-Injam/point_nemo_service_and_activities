// ─── Permanent fix: Windows "Unable to delete directory" during build ────────
// Java cannot delete directories held open by another process on Windows.
// This task delegates to cmd.exe `rd /s /q` which bypasses Java file-lock limits.
tasks.register("forceDeleteMergeAssets") {
    doFirst {
        val assetsDir = File("${layout.buildDirectory.get()}/intermediates/assets")
        if (assetsDir.exists()) {
            exec {
                commandLine("cmd", "/c", "rd", "/s", "/q", assetsDir.absolutePath)
                isIgnoreExitValue = true
            }
        }
    }
}

tasks.configureEach {
    if (name.startsWith("clean") && name.contains("Merge")) {
        dependsOn("forceDeleteMergeAssets")
    }
}
